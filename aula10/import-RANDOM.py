import random

print(random.random()) # Imprime um número aleatório entre 0 e 1
print(random.randint(1, 10)) # Imprime um número aleatório inteiro entre 1 e 10
print(random.choice(['a', 'b', 'c'])) # Imprime um elemento aleatório da lista
print(random.uniform(1.5, 10.5)) # Imprime um número aleatório float entre 1.5 e 10.5
